//! LSM `socket_connect` policy.
//!
//! # Why LSM?
//!
//! Classic tracepoints/kprobes can observe a `connect(2)`, but they cannot
//! deny it. LSM BPF runs at the kernel's security hook and may return a
//! negative errno to veto the operation. This makes LSM a natural fit for
//! mandatory access-control policies that are not tied to a cgroup
//! (`cgroup/connect4` is the cgroup-scoped alternative).
//!
//! # Hook contract
//!
//! `LSM_HOOK(int, 0, socket_connect, struct socket *sock,
//!           struct sockaddr *address, int addrlen)`.
//!
//! With aya's BTF argument convention, the context contains:
//!
//! * arg 0: `struct socket *` (unused here),
//! * arg 1: `struct sockaddr *` (kernel copy of the address),
//! * arg 2: `int addrlen`,
//! * arg 3: previous LSM program's return value (phony, always last).
//!
//! The program:
//!
//! 1. Defers to a previous LSM denial (`retval != 0`) without overriding it.
//! 2. Parses only `AF_INET` `sockaddr_in`; other families are passed through.
//! 3. Optionally restricts the policy to one UID.
//! 4. Denies configured destination ports with `-EPERM`.
//!
//! # Requirements
//!
//! `CONFIG_BPF_LSM=y`, `CONFIG_DEBUG_INFO_BTF=y`, and the BPF LSM enabled in
//! the `lsm=` boot parameter (for example `lsm=lockdown,yama,bpf`).
//!
//! `socket_connect` is a **sleepable** LSM hook (`sleepable_lsm_hooks` in
//! `kernel/bpf/bpf_lsm.c`), so the program must be compiled with
//! `#[lsm(sleepable, ...)]`. Attaching a non-sleepable program to this hook
//! fails with `EBUSY` at `bpf_raw_tracepoint_open` on modern kernels.

use aya_app_common::{LSM_ACTION_DENY, LsmConfig, LsmEvent, LsmStats};
use aya_ebpf::{
    EbpfContext as _,
    helpers::bpf_probe_read_kernel,
    macros::{lsm, map},
    maps::{Array, PerCpuArray, RingBuf},
    programs::LsmContext,
};

use crate::utils::{comm, cpu_stats, now_ns, port_in, sample};

/// `AF_INET` from `linux/socket.h` (libc-defined, not generated by aya).
const AF_INET: u16 = 2;
/// `EPERM`, returned as a negative errno to veto the connection.
const EPERM: i32 = 1;

#[map(name = "lsm_config")]
static LSM_CONFIG: Array<LsmConfig> = Array::with_max_entries(1, 0);

#[map(name = "lsm_stats")]
static LSM_STATS: PerCpuArray<LsmStats> = PerCpuArray::with_max_entries(1, 0);

#[map(name = "lsm_events")]
static LSM_EVENTS: RingBuf = RingBuf::with_byte_size(256 * 1024, 0);

/// Kernel `struct sockaddr_in` layout. This is UAPI-stable.
#[repr(C)]
#[derive(Clone, Copy)]
struct SockaddrIn {
    sin_family: u16,
    /// Network byte order.
    sin_port: u16,
    /// Raw network-order IPv4 address.
    sin_addr: u32,
    sin_zero: [u8; 8],
}

#[lsm(sleepable, hook = "socket_connect")]
pub fn lsm_socket_connect(ctx: LsmContext) -> i32 {
    try_lsm_socket_connect(&ctx).unwrap_or_else(|| {
        // Never let an internal error turn into a denial.
        0
    })
}

fn try_lsm_socket_connect(ctx: &LsmContext) -> Option<i32> {
    // Respect an earlier LSM program's decision. The phony retval argument is
    // always the last argument of the BTF context. LSM hooks may only return
    // 0 or a negative errno in [-4095, 0]; normalize any denial to -EPERM so
    // the verifier can prove the return range (the raw argument is a scalar
    // and `Option<i32>` construction otherwise widens it to u32).
    let previous: i32 = ctx.arg(3);
    if previous != 0 {
        return Some(if previous < 0 { -EPERM } else { 0 });
    }

    let cfg = LSM_CONFIG.get(0)?;
    let address: *const SockaddrIn = ctx.arg(1);
    let addr_len: i32 = ctx.arg(2);

    if let Some(stats) = cpu_stats(&LSM_STATS) {
        stats.connects += 1;
    }

    // A NULL address or a too-short buffer is not something we can classify;
    // pass it through.
    if address.is_null() || addr_len < core::mem::size_of::<SockaddrIn>() as i32 {
        if let Some(stats) = cpu_stats(&LSM_STATS) {
            stats.allowed += 1;
        }
        return Some(0);
    }

    // `socket_connect` receives a kernel copy of the sockaddr, so a kernel
    // read is correct. The helper is fault-tolerant.
    let addr: SockaddrIn = match unsafe { bpf_probe_read_kernel(address) } {
        Ok(addr) => addr,
        Err(_) => {
            if let Some(stats) = cpu_stats(&LSM_STATS) {
                stats.allowed += 1;
            }
            return Some(0);
        }
    };

    // Only IPv4 is parsed. IPv6 and AF_UNIX are passed through (and counted as
    // allowed) so that the policy cannot accidentally break them.
    if addr.sin_family != AF_INET {
        if let Some(stats) = cpu_stats(&LSM_STATS) {
            stats.allowed += 1;
        }
        return Some(0);
    }

    let dport = u16::from_be(addr.sin_port);

    // Optional UID restriction. `enforce_uid == 0` means every process.
    if cfg.enforce_uid != 0 && ctx.uid() != cfg.target_uid {
        if let Some(stats) = cpu_stats(&LSM_STATS) {
            stats.allowed += 1;
        }
        return Some(0);
    }

    if !port_in(&cfg.blocked_ports, cfg.blocked_port_count, dport) {
        if let Some(stats) = cpu_stats(&LSM_STATS) {
            stats.allowed += 1;
        }
        return Some(0);
    }

    if let Some(stats) = cpu_stats(&LSM_STATS) {
        stats.denied += 1;
    }

    if sample(cfg.event_sample) {
        crate::emit_event!(LSM_EVENTS, LsmEvent, {
            timestamp_ns: now_ns(),
            pid: ctx.pid(),
            uid: ctx.uid(),
            daddr: addr.sin_addr,
            dport: dport,
            family: addr.sin_family,
            action: LSM_ACTION_DENY,
            _pad: 0,
            comm: comm(ctx),
        });
    }

    // Negative errno vetoes connect(2).
    Some(-EPERM)
}
